export type CanvasActionId = keyof typeof CANVAS_ACTION_REGISTRY;

export function getCanvasActionDefinition(
  actionId?: string | null,
): CanvasActionDefinition | undefined {
  if (!actionId) return undefined;
  return CANVAS_ACTION_REGISTRY[actionId as CanvasActionId];
}

export function resolveCanvasActionBehavior(
  actionId: string,
  context: CanvasActionContext = {},
): CanvasActionBehavior | undefined {
  const definition = getCanvasActionDefinition(actionId);
  if (!definition) return undefined;
  return definition.resolveBehavior?.(context) ?? definition.defaultBehaviorType;
}

export function resolveCanvasActionCreatesNewRound(
  actionId: string,
  context: CanvasActionContext = {},
): boolean | undefined {
  const definition = getCanvasActionDefinition(actionId);
  if (!definition) return undefined;
  return typeof definition.createsNewRound === "function"
    ? definition.createsNewRound(context)
    : definition.createsNewRound;
}

export function resolveCanvasActionRequiresConfirmation(
  actionId: string,
  context: CanvasActionContext = {},
): boolean | undefined {
  const definition = getCanvasActionDefinition(actionId);
  if (!definition) return undefined;
  return typeof definition.requiresConfirmation === "function"
    ? definition.requiresConfirmation(context)
    : definition.requiresConfirmation;
}
