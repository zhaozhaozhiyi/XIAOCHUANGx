import type { SimulationEdge, SimulationNode } from "@/lib/chat-parts";

export type CanvasActionBehavior =
  | "local"
  | "prompt"
  | "confirm"
  | "snapshot"
  | "pending";

export type CanvasActionRisk = "low" | "medium" | "high";
export type CanvasActionSurface = "primary" | "more" | "hidden";

export type CanvasActionContext = {
  sessionId?: string;
  roundId?: string;
  selectedNode?: SimulationNode | null;
  selectedEdge?: SimulationEdge | null;
  hasWorldModel?: boolean;
  isViewingHistoricalRound?: boolean;
  runStatus?: "running" | "completed" | "waiting_user" | "failed";
  changesCoreBoundary?: boolean;
};

export type CanvasActionDefinition = {
  actionId: string;
  label: string;
  targetKind: string;
  defaultBehaviorType: CanvasActionBehavior;
  defaultSurface: CanvasActionSurface;
  risk: CanvasActionRisk;
  createsNewRound: boolean | ((context: CanvasActionContext) => boolean);
  requiresConfirmation: boolean | ((context: CanvasActionContext) => boolean);
  resolveBehavior?: (context: CanvasActionContext) => CanvasActionBehavior;
};

function defineAction(
  definition: CanvasActionDefinition,
): CanvasActionDefinition {
  return definition;
}

